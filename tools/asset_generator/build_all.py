def docs():
    d = os.path.join(ROOT, "docs"); os.makedirs(d, exist_ok=True)
    with open(f"{d}/palette.gpl", "w") as f:
        f.write("GIMP Palette\nName: DEAD FRONTIER Outpost\nColumns: 8\n#\n")
        for g, cols in PAL_GROUPS.items():
            for k, v in cols.items():
                r, gg, b = hexrgba(v)[:3]; f.write(f"{r:3d} {gg:3d} {b:3d}\t{k} ({g})\n")
    with open(f"{d}/ART_BIBLE.md", "w") as f:
        f.write("# DEAD FRONTIER: OUTPOST — Art Bible\n\nOne shared palette, one lighting model, one outline rule. Every asset is generated by `tools/asset_generator/` from this palette (`docs/palette.gpl`).\n\n## Colour palette\n")
        for g, cols in PAL_GROUPS.items():
            f.write(f"\n**{g}**\n\n| Name | HEX |\n|---|---|\n")
            for k, v in cols.items(): f.write(f"| `{k}` | `{v.upper()}` |\n")
        f.write("""
## Lighting direction
Single light source from the **top-left**. Highlights sit on top/left edges of every shape; shadows on bottom/right edges. Applied automatically per part by `core.shade()` (highlight x1.22, shadow x0.74 brightness).

## Outline rules
- 1 px selective outline, colour `outline` (#13151A), applied to the outer silhouette of every sprite after all parts are composited (`core.outline()`, 4-neighbour).
- No outline on terrain tiles (they must tile) or on semi-transparent overlays/UI placement indicators.
- Interior part separation is done with shading, not extra outlines.

## Shading rules
- Flat base colour + 1 px highlight edge + 1 px shadow edge per part; no gradients, no anti-aliasing.
- Weathering (rust speckle, grime) is deterministic seeded noise, heavier on edges.
- Semi-transparent alpha is used only for smoke, stains and UI overlays.

## Pixel density and sprite scale
- 1 art pixel = 1 texture pixel. Nearest-neighbour scaling only (integer multiples, e.g. x2 or x3 in-engine).
- Tile grid 32 px. Characters 32x32 (human ~ 24 px tall, brute fills ~26x26). Buildings 64x64 (2x2 tiles), ammo factory 96x96 (3x3 tiles), mine 32x32 (1 tile).

## Animation conventions
- Frames are equal-sized per animation; **pivot is identical for all frames** (characters: 16,27 = between the feet).
- Directions: `down`, `up`, `left`, `right`. `left` is a mirror of the `right` art.
- Frame counts: idle 4, walk/run 6, shoot 3, reload 6, attack 4, hit 2, death 6 (last frame is the held corpse).
- Turret barrels are drawn facing **east (+X)**; rotate the barrel sprite around pivot (32,32). Muzzle flashes and projectiles also face east.

## Naming conventions
- Frames: `<asset>_<anim>_<direction>_<NN>.png`  (direction omitted when `none`)
- Sheets (horizontal strips): `spritesheets/<category>/<asset>_<anim>[_<direction>].png`
- Buildings: `<name>_normal|damaged|destroyed.png`, turrets add `_base` / `_barrel`.
- Everything lower_snake_case. Full metadata lives in `docs/manifest.json`.
""")
    cats = {}
    for m in MAN: cats.setdefault(m['category'], []).append(m)
    with open(f"{d}/ASSET_MANIFEST.md", "w") as f:
        f.write("# Asset Manifest (generated from manifest.json)\n")
        for c, ms in cats.items():
            f.write(f"\n## {c}\n\n| Asset | Anim | Dir | Frames | Size | File |\n|---|---|---|---|---|---|\n")
            for m in ms: f.write(f"| {m['name']} | {m['animation']} | {m['direction']} | {m['frames']} | {m['frame_width']}x{m['frame_height']} | `{m['file']}` |\n")
    with open(f"{d}/GODOT_IMPORT.md", "w") as f:
        f.write("""# Importing into Godot 4 (not yet tested inside Godot)
1. Copy `DEAD_FRONTIER_ASSETS/` into the project (e.g. `res://assets/`).
2. Project Settings > Rendering > Textures > Default Texture Filter = **Nearest**. Select the PNGs > Import dock: Filter Off, Mipmaps Off, Compress Lossless.
3. Animated sprites: use `spritesheets/*` strips. AnimatedSprite2D > SpriteFrames > "Add frames from sprite sheet" with Horizontal = `frames`, Vertical = 1 (values in `manifest.json`), FPS = 1000 / `frame_duration_ms`. Or load the individual frames from the asset folders.
4. Pivots: `manifest.json` gives `pivot` in pixels from the top-left. Set `Sprite2D.offset = Vector2(size/2) - pivot` (characters: pivot (16,27)).
5. Turrets: Node2D with `_base` Sprite2D (static) + `_barrel` Sprite2D (centered, rotate it). Play the `recoil` strip on firing. Position the muzzle flash at barrel tip (~ +30,0 from the pivot, rotate with the barrel).
6. TileSet: tile size 32x32, import terrain PNGs as individual atlas sources (or build one atlas). Overlays (vegetation/debris/props) are free-standing Sprite2D.
7. 9-slice UI: StyleBoxTexture with `nine_slice` margin from the manifest.
8. Left-facing frames already exist; do not flip in code.
""")
    shutil.copy(os.path.join(os.path.dirname(os.path.abspath(__file__)), "README.md"), f"{d}/../../tools/asset_generator/README.md") if False else None

def imgs(**f):
    return [m for m in MAN if all(m.get(k) == v for k, v in f.items())]
def load(m, i=0): return Image.open(os.path.join(ROOT, m['frame_files'][i]))

def previews():
    pv = os.path.join(ROOT, "previews"); os.makedirs(pv, exist_ok=True)
    # characters: rows = char/anim, each row = 4 directions of full strips
    rows = []
    for kind in chars.PLAN:
        for anim in chars.PLAN[kind]:
            strips = [Image.open(os.path.join(ROOT, imgs(name=kind, animation=anim, direction=d)[0]['file'])) for d in chars.DIRS]
            gap = 8; w = sum(s.width for s in strips) + gap * 3; row = Image.new("RGBA", (w, 32), CLEAR); x = 0
            for s in strips: row.alpha_composite(s, (x, 0)); x += s.width + gap
            rows.append((f"{kind} {anim}  [down | up | left | right]", row))
    S = 2; W = max(r.width for _, r in rows) * S + 8; out = Image.new("RGBA", (W, len(rows) * (32 * S + 12) + 4), (34, 38, 41, 255)); dr = ImageDraw.Draw(out)
    for i, (l, r) in enumerate(rows):
        y = 4 + i * (32 * S + 12); dr.text((4, y), l, fill=(200, 205, 190, 255)); dr.rectangle([4, y + 11, 4 + r.width * S, y + 11 + 32 * S], fill=(48, 53, 57, 255))
        out.alpha_composite(r.resize((r.width * S, r.height * S), Image.NEAREST), (4, y + 11))
    out.save(f"{pv}/characters.png")
    # buildings
    items = [(m['file'].split('/')[-1][:-4], load(m)) for m in MAN if m['category'] == 'buildings' and m['kind'] == 'static']
    contact(items, 8, 2, cellw=192, cellh=192).save(f"{pv}/buildings.png")
    # environment (tiles + overlays + tiled demo)
    items = [(m['name'], load(m)) for m in MAN if m['category'] == 'environment']
    sheet = contact(items, 10, 2, cellw=128, cellh=64)
    g = lambda n: load(imgs(name=n)[0])
    names = [['grass_0', 'grass_1', 'grass_2', 'dirt_0', 'dirt_1', 'concrete_0', 'concrete_1', 'concrete_0'],
             ['grass_1', 'grass_0', 'dirt_0', 'dirt_1', 'concrete_1', 'concrete_0', 'cracked_concrete', 'rubble'],
             ['asphalt', 'road_edge_h', 'road_edge_h', 'road_edge_h', 'road_edge_h', 'road_edge_h', 'asphalt', 'asphalt'],
             ['asphalt', 'road_center_h', 'road_center_h', 'road_damaged_1', 'road_center_h', 'road_center_h', 'asphalt', 'asphalt'],
             ['asphalt', 'road_edge_h', 'road_edge_h', 'road_edge_h', 'road_edge_h', 'road_edge_h', 'asphalt', 'asphalt'],
             ['industrial_floor_0', 'industrial_floor_0', 'industrial_floor_1', 'metal_floor_0', 'metal_floor_0', 'metal_floor_1', 'industrial_grate', 'industrial_grate'],
             ['industrial_floor_0', 'industrial_floor_0', 'industrial_floor_1', 'metal_floor_0', 'metal_floor_0', 'metal_floor_1', 'industrial_grate', 'industrial_grate']]
    demo = new(8 * 32, len(names) * 32)
    for j, row in enumerate(names):
        for i, n in enumerate(row):
            t = g(n)
            if n == 'road_edge_h' and j == 4: t = flip_v(t)
            demo.alpha_composite(t, (i * 32, j * 32))
    demo.alpha_composite(g('car_wreck'), (4, 70)); demo.alpha_composite(g('barrel_rust'), (150, 60)); demo.alpha_composite(g('bush_0'), (180, 20)); demo.alpha_composite(g('sandbags_corner'), (200, 150)); demo.alpha_composite(g('crate_wood_l'), (110, 190))
    demo = demo.resize((demo.width * 2, demo.height * 2), Image.NEAREST)
    out = Image.new("RGBA", (max(sheet.width, demo.width), sheet.height + demo.height + 8), (34, 38, 41, 255)); out.paste(sheet, (0, 0)); out.paste(demo, (0, sheet.height + 8)); out.save(f"{pv}/environment.png")
    # effects
    rows = [(m['name'], Image.open(os.path.join(ROOT, m['file']))) for m in MAN if m['category'] == 'effects' and m['kind'] == 'animation']
    rows += [(m['name'], load(m)) for m in MAN if m['category'] == 'effects' and m['kind'] == 'static']
    S = 2; cw = max(r.width for _, r in rows) * S; out = Image.new("RGBA", (cw + 8, sum(r.height * S + 12 for _, r in rows) + 4), (34, 38, 41, 255)); dr = ImageDraw.Draw(out); y = 4
    for l, r in rows:
        dr.text((4, y), l, fill=(200, 205, 190, 255)); dr.rectangle([4, y + 11, 4 + r.width * S, y + 11 + r.height * S], fill=(40, 40, 44, 255)); out.alpha_composite(r.resize((r.width * S, r.height * S), Image.NEAREST), (4, y + 11)); y += r.height * S + 12
    out.save(f"{pv}/effects.png")
    # ui
    items = [(m['name'][:20], load(m)) for m in MAN if m['category'] == 'ui']
    contact(items, 8, 3, cellw=200, cellh=200).save(f"{pv}/ui.png")
    # overview
    pick = [load(imgs(name='player', animation='idle', direction='down')[0]), load(imgs(name='walker', animation='idle', direction='right')[0]),
            load(imgs(name='runner', animation='run', direction='right')[0], 1), load(imgs(name='brute', animation='attack', direction='down')[0], 2)]
    ov = [("player", pick[0]), ("walker", pick[1]), ("runner", pick[2]), ("brute", pick[3])]
    for n in ('scrap_collector', 'generator', 'repair_station', 'wall', 'machine_gun_turret', 'cannon_turret', 'mine'):
        ov.append((n, load(imgs(name=n, state='normal')[0] if n not in ('machine_gun_turret', 'cannon_turret') else imgs(name=n, part='base', state='normal')[0])))
    ov.append(("ammo_factory", load(imgs(name='ammo_factory', state='normal')[0])))
    for n in ('grass_0', 'dirt_0', 'concrete_0', 'asphalt', 'road_center_h', 'metal_floor_0', 'barrel_rust', 'car_wreck', 'sandbags_corner'): ov.append((n, g(n)))
    for n in ('explosion', 'fire', 'muzzle_flash_mg'): ov.append((n, load(imgs(name=n)[0], 3 if n != 'muzzle_flash_mg' else 1)))
    for n in ('icon_scrap', 'icon_health', 'icon_machine_gun', 'icon_upgrade'): ov.append((n, g(n)))
    contact(ov, 8, 2, cellw=192, cellh=192).save(f"{pv}/asset_overview.png")

